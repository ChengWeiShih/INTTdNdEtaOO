#!/usr/bin/env python3
"""
run_evt_vtxz_left_right.py - Orchestrator for EvtVtxZLeftRight HTCondor passes.

Usage:
    python3 run_evt_vtxz_left_right.py <config.py> --step 0
    python3 run_evt_vtxz_left_right.py <config.py> --step 1
    python3 run_evt_vtxz_left_right.py <config.py> --step 0 --dry-run
    python3 run_evt_vtxz_left_right.py <config.py> --step 0 --set _ClusAdcCut=30

Steps:
    0 - Generate header (.h), macro (.C), condor job (.job), shell script (.sh)
        into output_directory/generated_macro/
    1 - Same as step 0, then submit with condor_submit
"""

import argparse
import importlib.util
import os
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import Optional

FRAMEWORK_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(FRAMEWORK_DIR))
from EvtVtxZLeftRightConfig import EvtVtxZLeftRightConfig

_HEADER_PLACEHOLDER = "header_to_be_replace"


def log(msg: str, level: str = "INFO") -> None:
    tag = {"INFO": "[INFO]", "WARN": "[WARN]", "ERR": "[ERR ]", "STEP": "[STEP]"}.get(level, "[INFO]")
    print(f"{tag} {msg}")


def load_config(config_path: str, pre_inject: Optional[dict] = None) -> EvtVtxZLeftRightConfig:
    config_path = os.path.abspath(config_path)

    if pre_inject:
        with open(config_path) as f:
            src = f.read()
        for var, val in pre_inject.items():
            pattern = rf"^({re.escape(var)}\s*=\s*).*$"
            new_src, n = re.subn(pattern, rf"\g<1>{val}", src, flags=re.MULTILINE)
            if n == 0:
                log(f"--set: variable '{var}' not found in {config_path}", "WARN")
            else:
                log(f"--set: {var} = {val}")
            src = new_src
        import tempfile
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as tmp:
            tmp.write(src)
            config_path = tmp.name

    spec = importlib.util.spec_from_file_location("_cfg_module", config_path)
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(FRAMEWORK_DIR))
    spec.loader.exec_module(mod)

    if not hasattr(mod, "cfg"):
        raise AttributeError(f"Config file must define a variable 'cfg'. Not found in {config_path}")
    if not isinstance(mod.cfg, EvtVtxZLeftRightConfig):
        raise TypeError("'cfg' must be an EvtVtxZLeftRightConfig instance.")
    return mod.cfg


def parse_set_args(set_list: list) -> dict:
    result = {}
    for item in set_list:
        if "=" not in item:
            raise ValueError(f"--set argument must be VAR=VALUE, got: {item!r}")
        k, v = item.split("=", 1)
        result[k.strip()] = v.strip()
    return result


def _cpp_bool(v) -> str:
    return "true" if v else "false"


def _cpp_string(s: str) -> str:
    escaped = str(s).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _cpp_pair_double(p) -> str:
    return f"{{{p[0]}, {p[1]}}}"


def _cpp_pair_pair_double(p) -> str:
    return f"{{{{{p[0][0]}, {p[0][1]}}}, {{{p[1][0]}, {p[1][1]}}}}}"


def _default_input_filename(cfg: EvtVtxZLeftRightConfig) -> str:
    return cfg.input_file_name.format(process=0, run_num=cfg.run_number)


def _condor_input_filename(cfg: EvtVtxZLeftRightConfig) -> str:
    name = cfg.input_file_name
    name = name.replace("{process:05d}", "$INT(process_shift,%05d)")
    name = name.replace("{run_num:08d}", f"{cfg.run_number:08d}")
    name = name.replace("{run_num}", str(cfg.run_number))
    return name



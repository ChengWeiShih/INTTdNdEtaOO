def copy_and_patch_macro(cfg: EvtVtxZLeftRightConfig, header_path: str, out_dir: str) -> str:
    macro_name = f"Run_EvtVtxZLeftRight_{cfg.pass_name}"
    template_src = os.path.join(cfg.macro_template_dir, "Run_EvtVtxZLeftRight_template.C")
    macro_dst = os.path.join(out_dir, f"{macro_name}.C")

    if not os.path.isfile(template_src):
        raise FileNotFoundError(
            f"Template macro not found: {template_src}\n"
            f"Set cfg.macro_template_dir to the MacroGen_LeftRight directory."
        )

    Path(out_dir).mkdir(parents=True, exist_ok=True)
    shutil.copy2(template_src, macro_dst)
    log(f"Copied template   : {template_src}")
    log(f"             -> {macro_dst}")

    with open(macro_dst) as fh:
        src = fh.read()

    old_inc = f'#include "{_HEADER_PLACEHOLDER}"'
    new_inc = f'#include "{os.path.abspath(header_path)}"'
    if old_inc in src:
        src = src.replace(old_inc, new_inc, 1)
        log(f"Patched include   : '{_HEADER_PLACEHOLDER}' -> {os.path.abspath(header_path)}")
    else:
        log(f"WARNING: placeholder '{old_inc}' not found in template.", "WARN")

    old_func = "void Run_EvtVtxZLeftRight_template("
    new_func = f"void {macro_name}("
    if old_func in src:
        src = src.replace(old_func, new_func, 1)
        log(f"Patched func name : 'Run_EvtVtxZLeftRight_template' -> '{macro_name}'")
    else:
        log("WARNING: function signature not found in template.", "WARN")

    with open(macro_dst, "w") as fh:
        fh.write(src)

    return macro_dst


def copy_and_patch_shell(cfg: EvtVtxZLeftRightConfig, out_dir: str) -> str:
    template_src = os.path.join(cfg.macro_template_dir, "run_job_template.sh")
    sh_dst = os.path.join(out_dir, f"run_job_{cfg.pass_name}.sh")

    if not os.path.isfile(template_src):
        raise FileNotFoundError(f"Shell template not found: {template_src}")

    with open(template_src) as f:
        src = f.read()
    src = src.replace("sphenix_setup.sh -n ana.538", f"sphenix_setup.sh -n {cfg.sphenix_build}")

    with open(sh_dst, "w") as f:
        f.write(src)
    os.chmod(sh_dst, 0o755)

    log(f"Copied shell      : {template_src}")
    log(f"             -> {sh_dst}")
    return sh_dst


def generate_condor_job(cfg: EvtVtxZLeftRightConfig, job_file_path: str,
                        macro_path: str, sh_path: str) -> str:
    macro_name = os.path.splitext(os.path.basename(macro_path))[0]
    gen_dir = os.path.dirname(macro_path)

    content = textwrap.dedent(f"""\
        Universe           = vanilla
        Initialdir         = {gen_dir}
        Executable         = {sh_path}
        PeriodicHold       = (NumJobStarts>=1 && JobStatus == 1)
        concurrency_limits = CONCURRENCY_LIMIT_DEFAULT:{cfg.condor_concurrency_limit}
        request_memory     = {cfg.condor_request_memory}
        Priority           = {cfg.condor_priority}
        job_lease_duration = 86400

        runnumber          = {cfg.run_number}
        nEvents            = {cfg.n_events}
        input_directory    = {cfg.input_directory}
        job_offset         = {cfg.job_offset}
        process_shift      = $(Process) + $(job_offset)
        input_filename     = {_condor_input_filename(cfg)}
        output_directory   = {cfg.output_directory}
        macro_name         = {macro_name}

        Output             = $(output_directory)/cw_log/condor_$INT(process_shift,%05d).out
        Error              = $(output_directory)/cw_log/condor_$INT(process_shift,%05d).err
        Log                = $(output_directory)/cw_log/condor_$INT(process_shift,%05d).log
        Arguments          = "$INT(process_shift) $(runnumber) $(nEvents) $(output_directory) $(input_directory) $(input_filename) $(macro_name)"
        Queue {cfg.n_condor_jobs}
    """)

    Path(job_file_path).parent.mkdir(parents=True, exist_ok=True)
    with open(job_file_path, "w") as f:
        f.write(content)
    log(f"Wrote condor job  : {job_file_path}")
    return job_file_path


def run_cmd(cmd: str, dry: bool = False) -> int:
    log(f"  $ {cmd}")
    if dry:
        return 0
    result = subprocess.run(cmd, shell=True)
    return result.returncode


def validate_input_directory(cfg: EvtVtxZLeftRightConfig) -> None:
    if not os.path.isdir(cfg.input_directory):
        log(f"Input directory not found: {cfg.input_directory}", "ERR")
        log("Stop operation before generating files or submitting jobs.", "ERR")
        sys.exit(1)


def step_generate(cfg: EvtVtxZLeftRightConfig, dry: bool = False) -> None:
    log("-- Step 0: Generate files --------------------------------", "STEP")
    validate_input_directory(cfg)

    gen_dir = cfg.generated_dir()

    for d in [cfg.completed_dir(), cfg.condor_log_dir()]:
        if dry:
            log(f"[dry] Would create: {d}")
        else:
            Path(d).mkdir(parents=True, exist_ok=True)
            log(f"Ensured directory : {d}")

    if dry:
        macro_name = f"Run_EvtVtxZLeftRight_{cfg.pass_name}"
        log(f"[dry] Would generate header : {gen_dir}/{macro_name}_params.h")
        log(f"[dry] Would copy+patch macro -> {gen_dir}/{macro_name}.C")
        log(f"[dry] Would copy shell      -> {gen_dir}/run_job_{cfg.pass_name}.sh")
        log(f"[dry] Would write condor job: {gen_dir}/run_condor_{cfg.pass_name}.job")
        return

    hdr = generate_params_header(cfg, gen_dir)
    macro = copy_and_patch_macro(cfg, hdr, gen_dir)
    sh = copy_and_patch_shell(cfg, gen_dir)
    job_file = os.path.join(gen_dir, f"run_condor_{cfg.pass_name}.job")
    generate_condor_job(cfg, job_file, macro, sh)

    log("[STEP] File generation complete.")


def step_submit(cfg: EvtVtxZLeftRightConfig, dry: bool = False) -> None:
    step_generate(cfg, dry=dry)
    log("-- Step 1: Submit condor jobs -----------------------------", "STEP")
    job_file = os.path.join(cfg.generated_dir(), f"run_condor_{cfg.pass_name}.job")
    rc = run_cmd(f"condor_submit {job_file}", dry=dry)
    if rc != 0:
        log(f"condor_submit failed (exit {rc})", "ERR")
        sys.exit(rc)
    log("Jobs submitted successfully.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="EvtVtxZLeftRight HTCondor pass orchestrator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent(__doc__),
    )
    parser.add_argument("config", help="Path to a config .py file (must define 'cfg').")
    parser.add_argument("--step", choices=["0", "1"], default="0",
                        help="0 = generate files only (default); 1 = generate + submit")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print what would be done without executing.")
    parser.add_argument("--set", metavar="VAR=VALUE", action="append", default=[],
                        help="Override a top-level config variable before loading.")

    args = parser.parse_args()

    if args.dry_run:
        log("DRY-RUN mode - no files will be written or submitted.", "WARN")

    cfg = load_config(args.config, parse_set_args(args.set) if args.set else None)
    print(cfg.summary())

    if args.step == "0":
        step_generate(cfg, dry=args.dry_run)
    elif args.step == "1":
        step_submit(cfg, dry=args.dry_run)


if __name__ == "__main__":
    main()
